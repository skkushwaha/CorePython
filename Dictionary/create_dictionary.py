# create dictionary using {}
person = {"name": "Jessa", "country": "USA", "telephone": 1178}
print(person)

# create dictionary using dict()
person = dict({"name": "Jessa", "country": "USA", "telephone": 1178})
print(person)

# create dictionary as each item in pair sequence
person = dict([("name", "Jessa"), ("country", "USA"), ("telephone", 1178)])
print(person)

# create dictionary value as a list
person = {"name": "Jessa", "country": "USA", "telephone": [1178, 9912, 2231]}
print(person)