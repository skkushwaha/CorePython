# A general way to create a list
# create a list with integer numbers
num = [10, 20, 30, 40, 50]
print("Total list= ", num)
print(f'fist {num[0]}, last {num[-1]}')

# create a list with strings
name = ["Raju", "Vani", "Gopal", "Laxmi"]
print(f'First {name[0]}, last {name[-1]}')

# create a list  with different elements
x = [10, 20, 10.5, 2.55, "Ganesh", "Vishnu"]
print("Total list= ", x)
print(f'First {x[0]}, last {x[5]}')
